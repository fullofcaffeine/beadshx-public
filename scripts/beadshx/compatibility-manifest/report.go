package main

import (
	"fmt"
	"sort"
	"strings"
)

// renderReport projects the validated manifest into deterministic Markdown.
// It reads nothing but the manifest, so the report never states a claim that
// the JSON file does not record.
func renderReport(m Manifest, manifestPath string) string {
	var out strings.Builder
	line := func(format string, args ...any) {
		fmt.Fprintf(&out, format, args...)
		out.WriteString("\n")
	}
	profileIDs := make([]string, 0, len(m.Profiles))
	for _, profile := range m.Profiles {
		profileIDs = append(profileIDs, profile.ID)
	}
	affecting := map[string][]string{}
	for _, difference := range m.Differences {
		for _, command := range difference.Affects {
			affecting[command] = append(affecting[command], difference.ID)
		}
	}
	waived := map[string]bool{}
	for _, difference := range m.Differences {
		if difference.Disposition == dispositionWaived {
			for _, waiver := range m.Waivers {
				if waiver.ID == difference.Waiver && waiver.Status == waiverApproved {
					waived[difference.ID] = true
				}
			}
		}
	}

	upstream := m.Identity.Upstream
	line("# Compatibility report: %s %s", upstream.Project, upstream.Version)
	line("")
	line("<!-- Generated by scripts/beadshx/check-compatibility-manifest.sh --write-report. Do not edit. -->")
	line("")
	line("This report is generated from `%s`.", manifestPath)
	line("The JSON manifest is the authority: this page states nothing that the")
	line("manifest does not record. Run")
	line("`scripts/beadshx/check-compatibility-manifest.sh --write-report` after a")
	line("manifest change, and commit both files.")
	line("")
	line("## Target")
	line("")
	line("| Field | Value |")
	line("| --- | --- |")
	line("| Manifest | `%s` (schema version %d) |", m.Identity.ManifestID, m.SchemaVersion)
	line("| Upstream | %s %s at `%s` |", upstream.Project, upstream.Version, upstream.Commit)
	line("| Source lock | `%s` `%s` |", m.Identity.SourceLock.Path, m.Identity.SourceLock.Pointer)
	line("| Compiler lock | `%s` `%s` |", m.Identity.CompilerLock.Path, m.Identity.CompilerLock.Pointer)
	line("")

	instances := 0
	commandProfiles := 0
	green := 0
	for _, command := range m.Commands {
		instances += len(command.Profiles) * len(command.Activations)
		commandProfiles += len(command.Profiles)
		for _, result := range command.Verification {
			if isGreen(command, result, affecting[command.ID], waived) {
				green++
			}
		}
	}
	line("## Coverage totals")
	line("")
	line("The denominator is every command of the pinned inventory under every")
	line("command profile that has it: %d commands, %d command profiles, and %d", len(m.Commands), commandProfiles, instances)
	line("command instances when the normal and completion activations count")
	line("separately.")
	line("")
	line("**Green command profiles: %d of %d.** A command profile is green only when", green, commandProfiles)
	line("it is required and implemented, does not use a development fallback,")
	line("passes with complete scenario coverage, and every difference that affects")
	line("it is waived by an approved waiver. Implementation, verification, and")
	line("waivers are separate axes: none of them implies another.")
	line("")
	line("The ownership lane names the lane that owns the behavior, or that will own")
	line("it for a command that is not started.")
	line("")
	countTable(&out, "Ownership lane", m.Commands, func(c Command) string { return c.OwnershipLane },
		[]string{"haxe", "go_facade", "haxe_go_compiler", "development_fallback"})
	countTable(&out, "Implementation state", m.Commands, func(c Command) string { return c.ImplementationState },
		[]string{"not_started", "partial", "implemented"})
	countTable(&out, "Requirement state", m.Commands, func(c Command) string { return c.RequirementState },
		[]string{"required", "not_applicable", "unsupported"})
	tierOrder := make([]string, 0, len(m.WorkflowTiers.Records))
	for _, tier := range m.WorkflowTiers.Records {
		tierOrder = append(tierOrder, tier.ID)
	}
	countTable(&out, "Workflow tier", m.Commands, func(c Command) string { return c.WorkflowTier }, tierOrder)

	line("### Verification by profile")
	line("")
	line("A sampled pass covers only the listed scenarios, on that profile only.")
	line("")
	line("| Profile | Platform | Pass, complete | Pass, sampled | Fail | Blocked | Unknown |")
	line("| --- | --- | ---: | ---: | ---: | ---: | ---: |")
	for _, profile := range m.Profiles {
		counts := map[string]int{}
		for _, command := range m.Commands {
			for _, result := range command.Verification {
				if result.Profile != profile.ID {
					continue
				}
				key := result.State
				if key == verificationPass {
					key += "-" + result.Coverage
				}
				counts[key]++
			}
		}
		cgo := "CGO off"
		if profile.CgoEnabled {
			cgo = "CGO on"
		}
		line("| `%s` | %s/%s, %s | %d | %d | %d | %d | %d |", profile.ID, profile.GOOS, profile.GOARCH, cgo,
			counts["pass-complete"], counts["pass-sampled"], counts["fail"], counts["blocked"], counts["unknown"])
	}
	line("")

	line("### Reference axes")
	line("")
	line("`pending` means not inventoried yet. `none` needs negative evidence. An")
	line("empty list never stands for either.")
	line("")
	line("| Axis | Pending | Listed | None |")
	line("| --- | ---: | ---: | ---: |")
	for _, name := range []string{axisOutputs, axisErrors, axisData, axisEffects, axisNative, axisPerformance} {
		counts := map[string]int{}
		for _, command := range m.Commands {
			counts[axisOf(command, name).State]++
		}
		line("| %s | %d | %d | %d |", name, counts["pending"], counts["listed"], counts["none"])
	}
	line("")

	line("## D0 view")
	line("")
	line("D0 is a filtered view of this manifest: the approved daily-workflow tier.")
	line("D0 success never changes the full-compatibility denominator above.")
	line("")
	header := "| Command | Implementation |"
	rule := "| --- | --- |"
	for _, profile := range profileIDs {
		header += " `" + strings.TrimPrefix(profile, "prof:") + "` |"
		rule += " --- |"
	}
	line("%s", header)
	line("%s", rule)
	d0 := 0
	for _, command := range m.Commands {
		if command.WorkflowTier != "tier:D0" {
			continue
		}
		d0++
		row := fmt.Sprintf("| `%s` | %s |", command.ID, command.ImplementationState)
		for _, profile := range profileIDs {
			row += " " + verificationCell(command, profile) + " |"
		}
		line("%s", row)
	}
	line("")
	line("D0 holds %d commands.", d0)
	line("")

	line("## Missing evidence")
	line("")
	line("Commands that `bdhx` runs (partial or implemented) with a profile whose")
	line("verification is unknown or blocked:")
	line("")
	missing := 0
	for _, command := range m.Commands {
		if command.ImplementationState == "not_started" {
			continue
		}
		var profiles []string
		for _, result := range command.Verification {
			if result.State == "unknown" || result.State == "blocked" {
				profiles = append(profiles, "`"+strings.TrimPrefix(result.Profile, "prof:")+"`")
			}
		}
		if len(profiles) > 0 {
			missing++
			line("- `%s`: %s", command.ID, strings.Join(profiles, ", "))
		}
	}
	if missing == 0 {
		line("- None.")
	}
	line("")

	line("## Failures")
	line("")
	failures := 0
	for _, command := range m.Commands {
		for _, result := range command.Verification {
			if result.State == "fail" {
				failures++
				line("- `%s@%s`: %s", command.ID, strings.TrimPrefix(result.Profile, "prof:"), strings.Join(result.Evidence, ", "))
			}
		}
	}
	if failures == 0 {
		line("No verification record fails.")
	}
	line("")

	line("## Differences")
	line("")
	line("Only `waived` with an approved waiver is green. The other dispositions stay")
	line("visibly non-green.")
	line("")
	dispositions := map[string]int{}
	for _, difference := range m.Differences {
		dispositions[difference.Disposition]++
	}
	line("| Disposition | Differences |")
	line("| --- | ---: |")
	for _, disposition := range []string{"fix_planned", "decision_pending", "waived", "untriaged"} {
		line("| %s | %d |", disposition, dispositions[disposition])
	}
	line("")
	line("| Difference | Disposition | Task or waiver | Category | Commands | Summary |")
	line("| --- | --- | --- | --- | ---: | --- |")
	for _, difference := range m.Differences {
		link := difference.TrackingTask
		if difference.Waiver != "" {
			link = strings.TrimSpace(link + " " + difference.Waiver)
		}
		if link == "" {
			link = "none"
		}
		line("| `%s` | %s | %s | %s | %d | %s |", difference.ID, difference.Disposition, link, difference.Category,
			len(difference.Affects), cell(difference.Summary))
	}
	line("")

	line("## Waivers")
	line("")
	if len(m.Waivers) == 0 {
		line("The manifest records no waiver.")
	} else {
		line("| Waiver | Status | Decision | Differences | Commands | Review trigger |")
		line("| --- | --- | --- | --- | ---: | --- |")
		for _, waiver := range m.Waivers {
			decision := waiver.DecisionDate
			if decision == "" {
				decision = "none"
			}
			line("| `%s` | %s | %s | %s | %d | %s |", waiver.ID, waiver.Status, decision, strings.Join(waiver.Differences, ", "),
				len(waiver.Commands), cell(waiver.ReviewTrigger))
		}
	}
	line("")

	line("## Development fallbacks")
	line("")
	fallbacks := 0
	for _, command := range m.Commands {
		if command.OwnershipLane == "development_fallback" {
			fallbacks++
			line("- `%s`", command.ID)
		}
	}
	if fallbacks == 0 {
		line("No command uses the `development_fallback` lane.")
	}
	line("")

	line("## Registries")
	line("")
	line("| Registry | State | Owner | Records |")
	line("| --- | --- | --- | ---: |")
	for _, registry := range registryKinds() {
		value := registry.get(m)
		owner := value.Owner
		if owner == "" {
			owner = "none"
		}
		line("| %s | %s | %s | %d |", registry.name, value.State, owner, len(value.Records))
	}
	line("| workflowTiers | %s | none | %d |", m.WorkflowTiers.State, len(m.WorkflowTiers.Records))
	line("")

	line("## Source inventories")
	line("")
	line("| Inventory | Task | Path | SHA-256 |")
	line("| --- | --- | --- | --- |")
	for _, inventory := range m.SourceInventories {
		line("| `%s` | %s | `%s` | `%s` |", inventory.ID, inventory.Task, inventory.Path, inventory.Sha256)
	}
	line("")

	line("## Evidence")
	line("")
	line("| Evidence | Kind | Path |")
	line("| --- | --- | --- |")
	for _, evidence := range m.Evidence {
		line("| `%s` | %s | `%s` |", evidence.ID, evidence.Kind, evidence.Path)
	}
	line("")

	line("## Commands")
	line("")
	header = "| Command | Hidden | Lane | Implementation | Tier |"
	rule = "| --- | --- | --- | --- | --- |"
	for _, profile := range profileIDs {
		header += " `" + strings.TrimPrefix(profile, "prof:") + "` |"
		rule += " --- |"
	}
	header += " Differences |"
	rule += " ---: |"
	line("%s", header)
	line("%s", rule)
	for _, command := range m.Commands {
		hidden := "no"
		if command.Hidden {
			hidden = "yes"
		}
		row := fmt.Sprintf("| `%s` | %s | %s | %s | %s |", command.ID, hidden, command.OwnershipLane, command.ImplementationState,
			strings.TrimPrefix(command.WorkflowTier, "tier:"))
		for _, profile := range profileIDs {
			row += " " + verificationCell(command, profile) + " |"
		}
		row += fmt.Sprintf(" %d |", len(affecting[command.ID]))
		line("%s", row)
	}
	return out.String()
}

func isGreen(command Command, result Verification, differences []string, waived map[string]bool) bool {
	if command.RequirementState != "required" || command.ImplementationState != "implemented" ||
		command.OwnershipLane == "development_fallback" || result.State != verificationPass || result.Coverage != stateComplete {
		return false
	}
	for _, difference := range differences {
		if !waived[difference] {
			return false
		}
	}
	return true
}

func axisOf(command Command, name string) Axis {
	switch name {
	case axisOutputs:
		return command.Axes.Outputs
	case axisErrors:
		return command.Axes.Errors
	case axisData:
		return command.Axes.Data
	case axisEffects:
		return command.Axes.Effects
	case axisNative:
		return command.Axes.NativeBoundaries
	default:
		return command.Axes.Performance
	}
}

func verificationCell(command Command, profile string) string {
	for _, result := range command.Verification {
		if result.Profile != profile {
			continue
		}
		if result.State == verificationPass {
			return fmt.Sprintf("pass, %s (%d scenarios)", result.Coverage, len(result.Scenarios))
		}
		return result.State
	}
	return "n/a"
}

func cell(text string) string {
	return strings.ReplaceAll(normalizeSpace(text), "|", "\\|")
}

func countTable(out *strings.Builder, title string, commands []Command, key func(Command) string, order []string) {
	counts := map[string]int{}
	for _, command := range commands {
		counts[key(command)]++
	}
	fmt.Fprintf(out, "### %s\n\n| %s | Commands |\n| --- | ---: |\n", title, title)
	seen := map[string]bool{}
	for _, value := range order {
		seen[value] = true
		fmt.Fprintf(out, "| %s | %d |\n", value, counts[value])
	}
	var extra []string
	for value := range counts {
		if !seen[value] {
			extra = append(extra, value)
		}
	}
	sort.Strings(extra)
	for _, value := range extra {
		fmt.Fprintf(out, "| %s | %d |\n", value, counts[value])
	}
	out.WriteString("\n")
}
